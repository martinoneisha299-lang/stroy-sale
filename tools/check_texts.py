#!/usr/bin/env python3
"""Линтер текстов сайта.

Проверяет СОБРАННЫЕ html на формулировки, которые мы договорились не использовать:
география («с заводов Юга» — возим не только с Юга), обещания по оплате
(условия каждый раз разные), разговорные обороты и рекламные штампы.

Запуск после сборки генераторов:
    python3 tools/check_texts.py            — только нарушения
    python3 tools/check_texts.py --verbose  — со списком страниц

Правило добавляется одной строкой в BANNED. Если формулировка на сайте нужна
осознанно — вносим её в ALLOW, чтобы линтер не шумел.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent

# (регулярка, объяснение) — регистр не важен, пробелы уже нормализованы
BANNED = [
    # --- география: возим не только с Юга -----------------------------------
    (r"завод\w* юга", "география: возим кирпич не только с Юга"),
    (r"юга росси|юг росси", "география: сужает поставщиков до одного региона"),
    (r"южн\w+ завод", "география: сужает поставщиков до одного региона"),
    # --- оплата: условия каждый раз разные, обещать нельзя -------------------
    (r"оплата при получении", "оплата: обещание, которое не всегда выполнимо"),
    (r"плат\w+ при получении", "оплата: обещание, которое не всегда выполнимо"),
    (r"без предоплаты|предоплаты нет", "оплата: обещание, которое не всегда выполнимо"),
    (r"наличными или картой", "оплата: лишняя детализация расчёта с водителем"),
    (r"картой водителю|наличными водителю", "оплата: небезопасно и не всегда так"),
    # --- разговорный тон ----------------------------------------------------
    (r"\bвозим\b|\bпривезём\b|\bпривозим\b", "тон: разговорное, нужно «поставляем/доставляем»"),
    (r"куда берут", "тон: разговорное, нужно «применение»"),
    (r"побилось|побьётся", "тон: разговорное"),
    (r"спросите менеджера|скажите объём", "тон: перекладывает работу на покупателя"),
    (r"держит машину", "тон: разговорное описание характеристики"),
    (r"живые фото", "тон: разговорное"),
    (r"под дом и бюджет", "тон: разговорное"),
    (r"сэкономит деньги|сэкономить деньги", "тон: разговорное"),
    (r"забрать самому|заберёте сами", "тон: разговорное"),
    (r"ничего не нашли|не нашлось", "тон: разговорное сообщение интерфейса"),
    (r"\bпохуй\b|\bкороче\b|\bнормально\b", "тон: недопустимо на сайте"),
    # --- рекламные штампы ---------------------------------------------------
    (r"широкий ассортимент", "штамп: ничего не сообщает покупателю"),
    (r"лучшие цены|низкие цены|цены ниже рынка", "штамп и необоснованное заявление"),
    (r"индивидуальный подход", "штамп"),
    (r"команда профессионалов|профессионалы своего дела", "штамп"),
    (r"динамично развива", "штамп"),
    (r"высокое качество по доступной цене", "штамп"),
    (r"мы гарантируем", "обещание без основания"),
]

# Осознанные исключения: (регулярка нарушения, регулярка контекста-разрешения)
ALLOW = [
    # «Доставка по Краснодару и краю» — это про доставку, а не про происхождение
    (r"\bвозим\b", r"возим по краснодар"),
]

TAG = re.compile(r"<(script|style)[^>]*>.*?</\1>", re.S | re.I)
ANY_TAG = re.compile(r"<[^>]+>")
SPACE = re.compile(r"[\s  ]+")


def visible_text(html: str) -> str:
    """Видимый текст страницы + тексты из атрибутов, которые читает покупатель."""
    attrs = " ".join(
        m.group(2) for m in re.finditer(
            r'\b(alt|title|aria-label|placeholder|content)="([^"]*)"', html, re.I))
    body = ANY_TAG.sub(" ", TAG.sub(" ", html))
    return SPACE.sub(" ", f"{body} {attrs}").strip()


def allowed(pattern: str, text: str, pos: int) -> bool:
    """Нарушение попадает в осознанное исключение?"""
    window = text[max(0, pos - 40):pos + 60].lower()
    return any(re.search(ctx, window) for pat, ctx in ALLOW if pat == pattern)


def main() -> int:
    verbose = "--verbose" in sys.argv
    # design_handoff_stroysale — исходные макеты заказчика, не страницы сайта
    skip = {"design_handoff_stroysale", "node_modules"}
    pages = sorted(p for p in BASE.rglob("*.html")
                   if not any(part.startswith((".", "_")) or part in skip
                              for part in p.relative_to(BASE).parts))
    if not pages:
        print("Не нашёл ни одной страницы — сначала соберите сайт.")
        return 1

    hits: dict[tuple[str, str], list[tuple[str, str]]] = defaultdict(list)
    for page in pages:
        text = visible_text(page.read_text(encoding="utf-8")).lower()
        for pattern, why in BANNED:
            for m in re.finditer(pattern, text):
                if allowed(pattern, text, m.start()):
                    continue
                quote = text[max(0, m.start() - 30):m.end() + 30].strip()
                hits[(pattern, why)].append((str(page.relative_to(BASE)), quote))
                break  # одной находки на страницу достаточно

    print(f"Проверено страниц: {len(pages)}")
    if not hits:
        print("Запрещённых формулировок не найдено.")
        return 0

    total = sum(len(v) for v in hits.values())
    print(f"НАРУШЕНИЙ: {total} на {len({p for v in hits.values() for p, _ in v})} страницах\n")
    for (pattern, why), found in sorted(hits.items(), key=lambda kv: -len(kv[1])):
        print(f"  «{pattern}» — {why}")
        print(f"    страниц: {len(found)}, например: {found[0][0]}")
        print(f"    контекст: …{found[0][1]}…")
        if verbose:
            for page, _ in found[:20]:
                print(f"      {page}")
            if len(found) > 20:
                print(f"      … и ещё {len(found) - 20}")
        print()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
